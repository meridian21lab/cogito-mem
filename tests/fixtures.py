def claude_code_tool_work(session: str = "sess-t", day: str = "2026-10-12") -> list[dict]:
    """Two turns of tool calls: each ``tool_use`` in an assistant line of its own, its
    ``tool_result`` in the next user line (a failed command is ``is_error`` with ``Exit code N``)."""
    t = lambda mm, ss=0: f"{day}T10:{mm:02d}:{ss:02d}.000Z"  # noqa: E731
    base = {"isSidechain": False, "userType": "external", "cwd": "/work/app", "sessionId": session, "version": "2.1.0"}

    def say(n: int, role: str, text: str) -> dict:
        content = text if role == "user" else [{"type": "text", "text": text}]
        return {**base, "type": role, "uuid": f"{session}-m{n}", "timestamp": t(n),
                "message": {"role": role, "content": content}}  # fmt: skip

    def call(n: int, name: str, args: dict, result: str, error: bool = False) -> list[dict]:
        block = {"type": "tool_result", "tool_use_id": f"toolu_{n}", "content": result}
        if error:
            block["is_error"] = True
        return [
            {**base, "type": "assistant", "uuid": f"{session}-c{n}", "timestamp": t(n, 10), "message": {
                "id": f"msg_{n}", "role": "assistant", "content": [{"type": "tool_use", "id": f"toolu_{n}", "name": name, "input": args}]}},
            {**base, "type": "user", "uuid": f"{session}-r{n}", "timestamp": t(n, 20), "sourceToolAssistantUUID": f"{session}-c{n}",
             "toolUseResult": f"Error: {result}" if error else {"stdout": result}, "message": {"role": "user", "content": [block]}},
        ]  # fmt: skip

    test = "cd /work/app && python -m pytest -q tests/test_parser.py"
    return [
        say(0, "user", "The parser test fails on trailing commas, please fix it."),
        say(1, "assistant", "Let me run the tests first."),
        *call(1, "Bash", {"command": test, "description": "Run the parser tests"},
              "Exit code 1\nFAILED tests/test_parser.py::test_commas", error=True),
        *call(2, "Read", {"file_path": "/work/app/src/parser.py"}, "1\tdef parse(text):"),
        *call(3, "Edit", {"file_path": "/work/app/tests/test_parser.py", "old_string": "x", "new_string": "y"},
              "<tool_use_error>String to replace not found in file.</tool_use_error>", error=True),
        *call(4, "Edit", {"file_path": "/work/app/src/parser.py", "old_string": "a", "new_string": "b"},
              "The file /work/app/src/parser.py has been updated."),
        *call(5, "Read", {"file_path": "/home/me/notes/parser.md"}, "notes"),
        *call(6, "Bash", {"command": test.split("&& ")[1]}, "3 passed in 0.12s"),
        *call(7, "Bash", {"command": "OPENROUTER_API_KEY=abcd1234efgh5678 ./deploy.sh staging"}, "deployed"),
        *call(8, "Bash", {"command": "rm -rf build"},
              "The user doesn't want to proceed with this tool use. The tool use was rejected.", error=True),
        say(9, "assistant", "Fixed: the parser accepts trailing commas now."),
        say(10, "user", "Thanks. Note it in the README."),
        *call(11, "Write", {"file_path": "/work/app/README.md", "content": "the whole file"}, "File created successfully"),
        say(12, "assistant", "Done."),
    ]  # fmt: skip


def write_jsonl(path: Path, records: list[dict]) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("".join(_line(r) for r in records))
    return path


